#!/usr/bin/env python3
"""
Generates src/ui/fonts_tr.cpp / include/ui/fonts_tr.h: FreeSans bitmap fonts (same
rendering as Adafruit's fontconvert, so they look like LovyanGFX's FreeSans*pt7b)
plus the Turkish letters and the degree sign, using LovyanGFX's sparse EncodeRange.

  pip install freetype-py
  python3 tools/fonts/make_tr_fonts.py /usr/share/fonts/truetype/freefont          # 4" board
  python3 tools/fonts/make_tr_fonts.py /usr/share/fonts/truetype/freefont --ws5    # 5" board

--ws5 renders the same fonts 1.5x larger (800x480 panel, same physical size) into
src/ui/fonts_tr_ws5.cpp. Each file compiles only for its board (BOARD_WS5 guard).
"""
import os
import sys

import freetype

DPI = 141  # fontconvert default
RANGES = [(0x20, 0x7E), (0xB0, 0xB0), (0xC7, 0xC7), (0xD6, 0xD6), (0xDC, 0xDC),
          (0xE7, 0xE7), (0xF6, 0xF6), (0xFC, 0xFC), (0x11E, 0x11F), (0x130, 0x131),
          (0x15E, 0x15F)]
FONTS = [  # (C++ name, ttf file, point size)
    ("Sans8", "FreeSans.ttf", 8),
    ("Sans9", "FreeSans.ttf", 9),
    ("Sans12", "FreeSans.ttf", 12),
    ("Sans18", "FreeSans.ttf", 18),
    ("SansBold8", "FreeSansBold.ttf", 8),
    ("SansBold9", "FreeSansBold.ttf", 9),
    ("SansBold12", "FreeSansBold.ttf", 12),
    ("SansBold18", "FreeSansBold.ttf", 18),
    ("SansBold24", "FreeSansBold.ttf", 24),
]


def render(path, size, scale=1.0):
    face = freetype.Face(path)
    face.set_char_size(int(round(size * scale * 64)), 0, DPI, 0)
    bits = []
    glyphs = []
    for start, end in RANGES:
        for cp in range(start, end + 1):
            face.load_char(chr(cp), freetype.FT_LOAD_TARGET_MONO | freetype.FT_LOAD_RENDER)
            g = face.glyph
            bm = g.bitmap
            off = len(bits)
            for y in range(bm.rows):
                row = bm.buffer[y * bm.pitch:(y + 1) * bm.pitch]
                for x in range(bm.width):
                    bits.append((row[x >> 3] >> (7 - (x & 7))) & 1)
            glyphs.append((off // 8 if off % 8 == 0 else None, off, bm.width, bm.rows,
                           g.advance.x >> 6, g.bitmap_left, 1 - g.bitmap_top))
            # pad each glyph to a whole byte (fontconvert does the same)
            while len(bits) % 8:
                bits.append(0)
    data = bytearray()
    for i in range(0, len(bits), 8):
        b = 0
        for k in range(8):
            b = (b << 1) | bits[i + k]
        data.append(b)
    y_adv = face.size.height >> 6
    return data, [(o // 8, w, h, a, xo, yo) for (_, o, w, h, a, xo, yo) in glyphs], y_adv


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    ws5 = "--ws5" in sys.argv
    scale = 1.5 if ws5 else 1.0
    ttf_dir = args[0] if args else "/usr/share/fonts/truetype/freefont"
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    out = ['// Generated by tools/fonts/make_tr_fonts.py from GNU FreeFont (GPLv3 with font',
           '// exception). Do not edit by hand.',
           '#if defined(BOARD_WS5)' if ws5 else '#if !defined(BOARD_WS5)',
           '#include "ui/fonts_tr.h"', '', 
           'namespace ui::font {', '', 'namespace {', '']
    ranges = []
    base = 0
    for s, e in RANGES:
        ranges.append(f"{{0x{s:X}, 0x{e:X}, {base}}}")
        base += e - s + 1
    out.append("const lgfx::EncodeRange kRanges[] = {" + ", ".join(ranges) + "};")
    out.append("")
    footer = []
    for name, ttf, size in FONTS:
        data, glyphs, y_adv = render(os.path.join(ttf_dir, ttf), size, scale)
        out.append(f"const uint8_t k{name}Bitmap[] = {{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append(f"const lgfx::GFXglyph k{name}Glyphs[] = {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append("")
        footer.append(f"const lgfx::GFXfont {name}((uint8_t*)k{name}Bitmap, (lgfx::GFXglyph*)k{name}Glyphs, "
                      f"0x{RANGES[0][0]:X}, 0x{RANGES[-1][1]:X}, {y_adv}, {len(RANGES)}, const_cast<lgfx::EncodeRange*>(kRanges));")
        print(f"{name}: {len(data)} bitmap bytes, {len(glyphs)} glyphs, yAdvance {y_adv}")
    out.append("}  // namespace")
    out.append("")
    out += footer
    out += ["", "}  // namespace ui::font", "", "#endif", ""]
    name = "fonts_tr_ws5.cpp" if ws5 else "fonts_tr.cpp"
    with open(os.path.join(root, "src", "ui", name), "w") as f:
        f.write("\n".join(out))
    if ws5:
        return  # the header is shared
    hdr = ['#pragma once', '', '#include <lgfx/v1/lgfx_fonts.hpp>', '',
           '/**', ' * FreeSans bitmap fonts with Turkish letters (ÇÖÜĞİŞ çöüğış) and the degree sign.',
           ' * Strings are UTF-8; LovyanGFX decodes them. Generated by tools/fonts/make_tr_fonts.py.',
           ' */', 'namespace ui::font {', '']
    for name, _, size in FONTS:
        hdr.append(f"extern const lgfx::GFXfont {name};  // {size} pt")
    hdr += ['', '}  // namespace ui::font', '']
    with open(os.path.join(root, "include", "ui", "fonts_tr.h"), "w") as f:
        f.write("\n".join(hdr))


if __name__ == "__main__":
    main()
