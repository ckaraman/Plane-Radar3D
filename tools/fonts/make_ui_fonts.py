#!/usr/bin/env python3
"""
Generates the smooth (anti-aliased) fonts of the control screen: Inter (rsms.me/inter,
SIL Open Font License 1.1), 4-bit coverage per pixel, drawn by ui/ui_text.cpp.

  pip install freetype-py
  # Inter-4.x.zip from github.com/rsms/inter/releases, unzipped:
  python3 tools/fonts/make_ui_fonts.py path/to/extras/ttf          # 5" (800 x 480)
  python3 tools/fonts/make_ui_fonts.py path/to/extras/ttf --ws5b   # 5B (1024 x 600)

Writes src/ui/ui_fonts_ws5.cpp or src/ui/ui_fonts_ws5b.cpp (each compiles for its board).
"""
import os
import sys

import freetype

# Latin-1 and Latin Extended-A (Turkish and most European song titles), a few signs.
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x100, 0x17F), (0x2013, 0x2014), (0x2018, 0x2019),
          (0x201C, 0x201D), (0x2022, 0x2022), (0x2026, 0x2026), (0x266A, 0x266A)]
FONTS = [  # (C++ name, ttf, pixel size on the 800 x 480 panel)
    ("Ui13", "Inter-Medium.ttf", 13),
    ("Ui13b", "Inter-SemiBold.ttf", 13),
    ("Ui15b", "Inter-SemiBold.ttf", 15),
    ("Ui16", "Inter-Regular.ttf", 16),
    ("Ui18b", "Inter-SemiBold.ttf", 18),
    ("Ui22b", "Inter-SemiBold.ttf", 22),
]


def render(path, px):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, px)
    glyphs, data = [], bytearray()
    for start, end in RANGES:
        for cp in range(start, end + 1):
            if face.get_char_index(cp) == 0 and cp != 0x20:
                continue
            face.load_char(chr(cp), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
            g = face.glyph
            bm = g.bitmap
            w, h = bm.width, bm.rows
            off = len(data)
            nib = []
            for y in range(h):
                for x in range(w):
                    a = bm.buffer[y * bm.pitch + x] / 255.0
                    a = a ** 0.85  # a touch fuller: light text on a dark ground
                    nib.append(min(15, int(a * 15 + 0.5)))
            if len(nib) % 2:
                nib.append(0)
            for i in range(0, len(nib), 2):
                data.append((nib[i] << 4) | nib[i + 1])
            adv = (g.advance.x + 32) >> 6
            glyphs.append((cp, off, w, h, g.bitmap_left, -g.bitmap_top, adv))
    m = face.size
    return data, glyphs, (m.ascender + 32) >> 6, (-m.descender + 32) >> 6, (m.height + 32) >> 6


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    ws5b = "--ws5b" in sys.argv
    scale = 1.28 if ws5b else 1.0
    guard = '#if defined(BOARD_WS5B)' if ws5b else '#if defined(BOARD_WS5) && !defined(BOARD_WS5B)'
    ttf_dir = args[0]
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    out = ['// Generated by tools/fonts/make_ui_fonts.py from Inter (SIL Open Font License 1.1).',
           '// Do not edit by hand.', guard, '#include "ui/ui_text.h"', '', 'namespace ui::text {', '',
           'namespace {', '']
    footer = []
    for name, ttf, size in FONTS:
        px = int(round(size * scale))
        data, glyphs, asc, desc, line = render(os.path.join(ttf_dir, ttf), px)
        out.append(f"const uint8_t k{name}Bits[] = {{")
        for i in range(0, len(data), 20):
            out.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
        out.append("};")
        out.append(f"const Glyph k{name}Glyphs[] = {{")
        for g in glyphs:
            out.append("    {0x%X, %d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append("")
        footer.append(f"const Font {name} = {{k{name}Bits, k{name}Glyphs, {len(glyphs)}, {asc}, {desc}, {line}}};")
        print(f"{name}: {px} px, {len(data)} bytes, {len(glyphs)} glyphs")
    out += ["}  // namespace", ""] + footer + ["", "}  // namespace ui::text", "", "#endif", ""]
    name = "ui_fonts_ws5b.cpp" if ws5b else "ui_fonts_ws5.cpp"
    with open(os.path.join(root, "src", "ui", name), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
